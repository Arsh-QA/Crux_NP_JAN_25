package reviseBitMasking;

public class ShiftOperator {
	public static void main(String[] args) {

		int n = 10;
		System.out.println(n >> 1);

		int a = -11;
		System.out.println(a >> 1);
		
		int b = -12;
		System.out.println(b >> 1);
		
		int c = 15;
		System.out.println(c << 1);
		
		int d = -15;
		System.out.println(d << 1);


	}
}